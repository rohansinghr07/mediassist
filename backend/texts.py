_HI_DAYS = ["सोम", "मंगल", "बुध", "गुरु", "शुक्र", "शनि", "रवि"]
_HI_MONTHS = ["जन", "फ़र", "मार्च", "अप्रैल", "मई", "जून", "जुलाई", "अग", "सित", "अक्टू", "नव", "दिस"]


def fmt_date(d, lang: str) -> str:
    if isinstance(d, datetime):
        d = d.date()
    if isinstance(d, str):
        d = date.fromisoformat(d)
    if lang == "hi":
        return f"{_HI_DAYS[d.weekday()]}, {d.day} {_HI_MONTHS[d.month - 1]}"
    return d.strftime("%a, %d %b")


def fmt_time(dt: datetime, lang: str) -> str:
    return dt.strftime("%I:%M %p").lstrip("0")


def dept_name(dept: dict, lang: str) -> str:
    if not dept:
        return ""
    return dept.get("name_hi") if lang == "hi" and dept.get("name_hi") else dept.get("name_en", dept.get("_id", ""))
